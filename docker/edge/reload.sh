#!/bin/sh
# Перечитывать конфигурацию раз в половину суток.
#
# Certbot меняет файл сертификата в своём контейнере, а nginx держит открытым
# старый: без перезагрузки браузеры увидят просроченный сертификат ровно на
# 90-й день, и до этого дня ничто об этом не скажет.
#
# Отдельным файлом в /docker-entrypoint.d/, а НЕ подменой CMD. Официальный
# образ запускает подстановку переменных в шаблоны только если команда
# начинается с `nginx`:
#
#     if [ "$1" = "nginx" -o "$1" = "nginx-debug" ]; then ... fi
#
# Подменённая на `sh -c` команда пропускала этот шаг молча — конфиг не
# собирался, оставался стоковый default.conf, и домен отвечал страницей
# «Welcome to nginx» по http.
set -e
( while :; do sleep 12h; nginx -s reload 2>/dev/null || true; done ) &
