"""Кого подвинуть, чтобы освободить узлы под аренду.

Главная механика платформы и главный источник тихих поломок: уступают тут живые
работающие модели. Всё, что ниже, проверяет один принцип — сначала считаем
целиком, потом трогаем.
"""

from __future__ import annotations

import pytest

from looma.orchestrator.preemption import Standing, plan


def стоит(group_id, nodes, *, at=1000.0, protected=False, label=""):
    return Standing(group_id=group_id, label=label or group_id, nodes=nodes,
                    submitted_at=at, protected=protected)


# --------------------------------------------------------- ничего не трогаем
def test_свободных_хватает_никого_не_снимаем():
    сделано = plan(need=2, free=["n1", "n2", "n3"], standing=[стоит("m1", ["n4"])])
    assert сделано.possible and сделано.evict == []
    assert сделано.nodes == ["n1", "n2"]


def test_ноль_узлов_это_отказ():
    assert not plan(need=0, free=["n1"], standing=[]).possible


def test_повторы_в_свободных_не_считаются_дважды():
    """Иначе один узел, названный дважды, выглядит как два, и аренда встанет
    на половине заказанного."""
    сделано = plan(need=2, free=["n1", "n1"], standing=[])
    assert not сделано.possible


# ------------------------------------------------------------- вытеснение
def test_не_хватает_снимаем_модель():
    сделано = plan(need=2, free=["n1"], standing=[стоит("m1", ["n2"])])
    assert сделано.possible
    assert [s.group_id for s in сделано.evict] == ["m1"]
    assert сделано.nodes == ["n1", "n2"]


def test_снимаем_ту_что_освобождает_больше():
    """Меньше снятых моделей при том же результате."""
    сделано = plan(need=3, free=[],
                   standing=[стоит("мелкая", ["n1"]), стоит("крупная", ["n2", "n3", "n4"])])
    assert [s.group_id for s in сделано.evict] == ["крупная"]


def test_при_равенстве_снимаем_позже_развёрнутую():
    """У давно стоящей больше шансов, что на неё кто-то полагается."""
    сделано = plan(need=1, free=[],
                   standing=[стоит("старая", ["n1"], at=100.0),
                             стоит("свежая", ["n2"], at=900.0)])
    assert [s.group_id for s in сделано.evict] == ["свежая"]


def test_снимаем_ровно_столько_сколько_нужно():
    сделано = plan(need=2, free=[],
                   standing=[стоит("m1", ["n1", "n2"]), стоит("m2", ["n3", "n4"])])
    assert len(сделано.evict) == 1


def test_план_одинаков_при_одинаковом_входе():
    """Объяснить оператору, почему сняли именно это, можно только если ответ
    воспроизводим."""
    стоящие = [стоит("a", ["n1"], at=5.0), стоит("b", ["n2"], at=5.0),
               стоит("c", ["n3"], at=5.0)]
    первый = plan(need=2, free=[], standing=стоящие)
    второй = plan(need=2, free=[], standing=list(reversed(стоящие)))
    assert [s.group_id for s in первый.evict] == [s.group_id for s in второй.evict]


# --------------------------------------------------------------- защита
def test_защищённое_не_снимается_никогда():
    """Модель, на которой висит витрина, не должна падать оттого, что кто-то
    арендовал кластер."""
    сделано = plan(need=1, free=[], standing=[стоит("витрина", ["n1"], protected=True)])
    assert not сделано.possible
    assert "защищены" in сделано.refusal


def test_защищённое_обходится_если_есть_другое():
    сделано = plan(need=1, free=[],
                   standing=[стоит("витрина", ["n1"], protected=True),
                             стоит("обычная", ["n2"])])
    assert [s.group_id for s in сделано.evict] == ["обычная"]


# ---------------------------------------------------------------- отказ
def test_не_хватает_даже_со_снятием_всего():
    """Худшая развязка — модели сняты, аренда не встала, никто не работает.
    Поэтому сначала план целиком, и только потом действие."""
    сделано = plan(need=5, free=["n1"], standing=[стоит("m1", ["n2"])])
    assert not сделано.possible
    assert сделано.evict == [] and сделано.nodes == []


def test_отказ_называет_числа():
    сделано = plan(need=5, free=["n1"], standing=[стоит("m1", ["n2"])])
    assert "нужно 5" in сделано.refusal and "свободно 1" in сделано.refusal


def test_общие_узлы_не_считаются_дважды():
    """Две группы на одном узле освобождают один узел, а не два."""
    сделано = plan(need=2, free=[],
                   standing=[стоит("m1", ["n1"]), стоит("m2", ["n1"])])
    assert not сделано.possible


# --------------------------------------------------------------- объяснение
def test_объяснение_называет_снятых():
    сделано = plan(need=2, free=["n1"], standing=[стоит("m1", ["n2"], label="qwen3")])
    assert "qwen3" in сделано.explain()


def test_объяснение_без_снятия_говорит_о_свободных():
    assert "свободных" in plan(need=1, free=["n1"], standing=[]).explain()
