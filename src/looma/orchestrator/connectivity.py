"""Кто с кем может договориться напрямую, и что делать, если никто.

Данных о конкретной ПАРЕ узлов у оркестратора нет: узлы докладывают о себе, а
не друг о друге. Поэтому здесь топологическое правило, а не измерение — то же,
на чём стоит выбор пути в агенте.

Зачем это понадобилось. Конвейеру всё равно: он шлёт около восьми килобайт на
токен, и лишний крюк через реле терпим. Ray гоняет через тот же путь весь свой
object store, и реле в середине превращается ровно в ту конструкцию, которую
мы у других считаем недостатком — шлюз в пути постоянно.

Отсюда две разные вещи, которые легко перепутать:

  предпочтение   узлы, способные встретиться напрямую, идут первыми
  отказ          только когда встретиться нельзя ВООБЩЕ — ни прямо, ни через
                 реле, потому что реле не развёрнуто

Второе — единственный случай, когда Ray действительно не поедет. Первое — это
«поедет медленнее», и запрещать его нельзя: узел за симметричным NAT остаётся
полезной машиной.
"""

from __future__ import annotations

from typing import Dict, List, Sequence


def can_meet(a: dict, b: dict) -> bool:
    """Есть ли шанс у этой пары соединиться напрямую.

    Достаточно, чтобы хотя бы один принимал входящие: второй дозвонится до
    него. Если оба за NAT, остаётся пробивание дырок, а оно почти никогда не
    работает, когда хоть один NAT симметричный — такой даёт каждому адресату
    свой порт, и пробитое отверстие ведёт не туда, куда нужно.
    """
    if a.get("reachable") or b.get("reachable"):
        return True
    return not (a.get("symmetric_nat") or b.get("symmetric_nat"))


def score(node: dict) -> tuple:
    """Насколько узел удобен соседям. Больше — лучше, для сортировки по убыванию.

    Порядок полей и есть приоритет: принимающий входящие ценнее всего, потому
    что через него встречается кто угодно; симметричный NAT хуже обычного;
    дальше — сколько обменов у этого узла исторически шло напрямую.
    """
    return (
        1 if node.get("reachable") else 0,
        0 if node.get("symmetric_nat") else 1,
        float(node.get("direct_share") or 0.0),
    )


def prefer_meshy(nodes: Sequence[dict]) -> List[dict]:
    """Те, кто легче сходится, первыми — при прочих равных больше VRAM.

    Не отказ, а порядок: если связных узлов не хватит, дальше пойдут остальные,
    и кластер соберётся через реле.
    """
    return sorted(nodes, key=lambda n: (score(n), n.get("vram_free_bytes", 0)),
                  reverse=True)


def pairs_needing_relay(nodes: Sequence[dict]) -> List[tuple]:
    """Пары, которым без реле не встретиться. Пусто — значит сойдутся сами.

    Узел с самим собой — не пара: два ранга на одной машине разговаривают по
    настоящему локалхосту, и сеть между ними не участвует вовсе. Без этой
    оговорки узел за симметричным NAT «не мог соединиться сам с собой», и
    группа из двух рангов на нём отвергалась — при том, что это единственная
    конфигурация, которой связность не нужна в принципе.
    """
    stuck = []
    for i, a in enumerate(nodes):
        for b in nodes[i + 1:]:
            if a.get("node_id") and a.get("node_id") == b.get("node_id"):
                continue
            if not can_meet(a, b):
                stuck.append((a.get("node_id", ""), b.get("node_id", "")))
    return stuck


def verdict(nodes: Sequence[dict], *, relay_available: bool) -> Dict:
    """Соберётся ли такая группа, и какой ценой.

    Возвращает решение и его причину словами: «кластер не собрался» без
    объяснения — худшее, что может увидеть оператор, потому что дальше он
    пойдёт искать поломку в своём коде.
    """
    stuck = pairs_needing_relay(nodes)
    if not stuck:
        return {"ok": True, "path": "direct", "relayed_pairs": [], "why": ""}
    if relay_available:
        return {
            "ok": True, "path": "relay", "relayed_pairs": stuck,
            "why": (f"{len(stuck)} пар(ы) узлов не встретятся напрямую и пойдут "
                    "через реле: для Ray это заметно медленнее, чем для "
                    "конвейера — через тот же путь идёт весь его обмен"),
        }
    return {
        "ok": False, "path": "none", "relayed_pairs": stuck,
        "why": (f"эти узлы не могут соединиться: {_named(stuck)}. Прямой линк "
                "между ними невозможен, а реле не развёрнуто — поднимите его "
                "(docs/P2P_RELAY.md) или возьмите другие узлы"),
    }


def _named(pairs: Sequence[tuple], limit: int = 3) -> str:
    shown = ", ".join(f"{a}↔{b}" for a, b in pairs[:limit])
    return shown + (f" и ещё {len(pairs) - limit}" if len(pairs) > limit else "")
